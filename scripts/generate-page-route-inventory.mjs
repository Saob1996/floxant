import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, "out");
const SITEMAP_FILE = path.join(OUT_DIR, "sitemap.xml");
const OUTPUT_FILE = path.join(ROOT, "lib", "content", "generated-page-route-inventory.ts");

function walkFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true })
    .sort((left, right) => left.name < right.name ? -1 : left.name > right.name ? 1 : 0)
    .flatMap((entry) => {
      const absolute = path.join(directory, entry.name);
      return entry.isDirectory() ? walkFiles(absolute) : [absolute];
    });
}

function routeFromHtmlFile(file) {
  const relative = path.relative(OUT_DIR, file).replaceAll(path.sep, "/");
  if (relative === "index.html") return "/";
  if (/^google[a-z0-9_-]+\.html$/i.test(relative)) return `/${relative}`;
  if (relative.endsWith("/index.html")) return `/${relative.slice(0, -"/index.html".length)}`;
  return `/${relative.replace(/\.html$/i, "")}`;
}

function decodeHtml(value) {
  const named = { amp: "&", apos: "'", gt: ">", lt: "<", nbsp: " ", quot: '"' };
  return String(value ?? "")
    .replace(/&#(\d+);/g, (_, item) => String.fromCodePoint(Number(item)))
    .replace(/&#x([0-9a-f]+);/gi, (_, item) => String.fromCodePoint(Number.parseInt(item, 16)))
    .replace(/&([a-z]+);/gi, (match, name) => named[name.toLowerCase()] ?? match);
}

function attributes(tag) {
  const result = new Map();
  for (const match of tag.matchAll(/([^\s=/>]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/g)) {
    result.set(match[1].toLowerCase(), decodeHtml(match[2] ?? match[3] ?? match[4] ?? ""));
  }
  return result;
}

function normalizeRoute(value) {
  if (!value) return null;
  try {
    const pathname = new URL(value, "https://www.floxant.de").pathname;
    return pathname === "/" ? "/" : pathname.replace(/\/$/, "");
  } catch {
    const route = String(value).split(/[?#]/)[0];
    return route === "/" ? "/" : `/${route.replace(/^\/+|\/+$/g, "")}`;
  }
}

function metaRobots(html) {
  for (const tag of html.match(/<meta\b[^>]*>/gi) ?? []) {
    const data = attributes(tag);
    if ((data.get("name") ?? "").toLowerCase() === "robots") return data.get("content") ?? "";
  }
  return "";
}

function canonicalRoute(html) {
  for (const tag of html.match(/<link\b[^>]*>/gi) ?? []) {
    const data = attributes(tag);
    if ((data.get("rel") ?? "").toLowerCase().split(/\s+/).includes("canonical")) {
      return normalizeRoute(data.get("href") ?? "");
    }
  }
  return null;
}

function loadSitemap() {
  if (!fs.existsSync(SITEMAP_FILE)) throw new Error("out/sitemap.xml is missing");
  return new Set(
    [...fs.readFileSync(SITEMAP_FILE, "utf8").matchAll(/<loc>([\s\S]*?)<\/loc>/gi)]
      .map((match) => normalizeRoute(decodeHtml(match[1])))
      .filter(Boolean),
  );
}

function serializeInventory(entries) {
  const records = entries.map((entry) =>
    `  { route: ${JSON.stringify(entry.route)}, locale: ${JSON.stringify(entry.locale)}, indexable: ${entry.indexable}, sitemap: ${entry.sitemap}, canonicalRoute: ${entry.canonicalRoute === null ? "null" : JSON.stringify(entry.canonicalRoute)} },`
  );
  return [
    "// Generated by scripts/generate-page-route-inventory.mjs from out/. Do not edit by hand.",
    "export type GeneratedPageRouteInventoryEntry = {",
    "  route: string;",
    '  locale: "de" | "en";',
    "  indexable: boolean;",
    "  sitemap: boolean;",
    "  canonicalRoute: string | null;",
    "};",
    "",
    "export const generatedPageRouteInventory = [",
    ...records,
    "] as const satisfies readonly GeneratedPageRouteInventoryEntry[];",
    "",
  ].join("\n");
}

if (!fs.existsSync(OUT_DIR)) {
  console.error("PAGE_ROUTE_INVENTORY_ERROR out/ is missing");
  process.exit(1);
}

let sitemap;
try {
  sitemap = loadSitemap();
} catch (error) {
  console.error(`PAGE_ROUTE_INVENTORY_ERROR ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}

const entriesByRoute = new Map();
for (const file of walkFiles(OUT_DIR).filter((candidate) => candidate.toLowerCase().endsWith(".html"))) {
  const html = fs.readFileSync(file, "utf8");
  const route = routeFromHtmlFile(file);
  const robots = metaRobots(html);
  const entry = {
    route,
    locale: route === "/en" || route.startsWith("/en/") ? "en" : "de",
    indexable: !/\bnoindex\b/i.test(robots),
    sitemap: sitemap.has(route),
    canonicalRoute: canonicalRoute(html),
  };
  const existing = entriesByRoute.get(route);
  if (existing && JSON.stringify(existing) !== JSON.stringify(entry)) {
    console.error(`PAGE_ROUTE_INVENTORY_ERROR conflicting HTML outputs for ${route}`);
    process.exit(1);
  }
  entriesByRoute.set(route, entry);
}

const entries = [...entriesByRoute.values()].sort((left, right) =>
  left.route < right.route ? -1 : left.route > right.route ? 1 : 0
);
const output = serializeInventory(entries);
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  const current = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, "utf8") : "";
  if (current !== output) {
    console.error("PAGE_ROUTE_INVENTORY_CHECK status=FAIL generated inventory is stale");
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, output, "utf8");
}

const indexable = entries.filter((entry) => entry.indexable).length;
const inSitemap = entries.filter((entry) => entry.sitemap).length;
const aliases = entries.filter((entry) => entry.canonicalRoute && entry.canonicalRoute !== entry.route).length;
const missingCanonical = entries.filter((entry) => entry.canonicalRoute === null).length;
console.log(`PAGE_ROUTE_INVENTORY routes=${entries.length} indexable=${indexable} sitemap=${inSitemap} aliases=${aliases} missingCanonical=${missingCanonical} status=PASS`);
